/**
 * @file: src/hooks/useKeepScreenOn.ts
 * @description:
 *   Не давать экрану гаснуть, пока водитель в рабочей части приложения.
 *
 *   ЗАЧЕМ. Водитель смотрит на карту и на карточку заказа, а экран уходит в
 *   сон через полминуты — и за рулём приходится тыкать в телефон, чтобы
 *   увидеть, куда ехать.
 *
 *   ПОЧЕМУ ЭТО ПОЯВИЛОСЬ ТОЛЬКО В 1.5.42. Настройка `keepScreenOn` лежала в
 *   сторе с v1.5.19, пакет `expo-keep-awake` стоял в зависимостях — и ни
 *   одной строчки, которая бы это применяла, и ни одного переключателя в
 *   интерфейсе. Настройка хранилась и не делала ничего.
 *
 *   ПОЧЕМУ ОДНА БЛОКИРОВКА, А НЕ ДВЕ (1.5.57). До 1.5.57 корневой `_layout`
 *   держал ещё и безусловный `useKeepAwake()`. Из-за него переключатель
 *   «Не гасить экран» не выключал ничего: настройка снимала свою блокировку,
 *   а корневая продолжала держать флаг. Настройка, которая не работает, хуже
 *   отсутствующей — водитель считает, что распорядился, и не понимает, почему
 *   телефон ведёт себя иначе. Осталась одна блокировка, у настройки.
 *
 *   ПОЧЕМУ БЛОКИРОВКА ПЕРЕСТАВЛЯЕТСЯ ПРИ ВОЗВРАТЕ ИЗ ФОНА. На Android это не
 *   «режим», а ФЛАГ ОКНА текущей Activity (`FLAG_KEEP_SCREEN_ON`), и ставится
 *   он ровно один раз — при монтировании. Если этот единственный вызов
 *   промахнулся (Activity ещё не привязана — нативный модуль бросает
 *   `AppContextLost`), второй попытки не было НИКОГДА: эффект больше не
 *   выполняется, а `activate` с тем же тегом — no-op, пока тег числится
 *   активным. Возврат на передний план — дешёвый и надёжный повод
 *   попробовать снова, парой `deactivate` + `activate` (одним `activate`
 *   флаг не вернуть, см. выше про no-op).
 *
 *   ЧЕСТНО О ГРАНИЦАХ ЭТОЙ ПРАВКИ. Жалоба «экран опять начал гаснуть»
 *   (10.09.2026) ВОСПРОИЗВЕДЕНА НЕ БЫЛА. Проверял на эмуляторе через
 *   `always_finish_activities=1`: и новая сборка, и старая одинаково
 *   восстанавливают блокировку после пересоздания Activity
 *   (`dumpsys power` → `SCREEN_BRIGHT_WAKE_LOCK 'WindowManager/displayId:0'`
 *   появляется заново). То есть версия «потерялся флаг окна» проверку не
 *   прошла, и причина на телефоне водителя пока неизвестна. Поэтому здесь и
 *   появилась запись в журнал: следующая жалоба придёт уже с ответом на
 *   вопрос «блокировка не встала» или «настройка выключена».
 *
 * @dependencies: expo-keep-awake, react-native (AppState), @/stores/settings.store,
 *   @/services/logger.service
 * @created: 2026-09-08 (1.5.42)
 * @updated: 2026-09-10 (1.5.57 — блокировка переставляется при возврате из фона)
 */

import { useEffect } from 'react';
import { AppState } from 'react-native';
import { activateKeepAwakeAsync, deactivateKeepAwake } from 'expo-keep-awake';
import { useSettingsStore } from '@/stores/settings.store';
import { driverLogger } from '@/services/logger.service';

/**
 * Тег блокировки. Свой, а не общий: с тегом снятие не трогает чужие
 * блокировки, которые может ставить сам Expo.
 */
const TAG = 'ts-driver-screen';

/**
 * Поставить блокировку заново — со снятием, а не поверх.
 *
 * Промах не должен ронять экран: не удержали подсветку — обидно, но
 * работать приложению не мешает. Оба вызова могут отказать законно: пока
 * Activity нет (приложение поднимается в фоне), нативный модуль бросает
 * `AppContextLost`.
 */
async function reassertLock(reason: string): Promise<void> {
  try {
    await deactivateKeepAwake(TAG);
  } catch {
    // Блокировки могло не быть — снимать нечего.
  }
  try {
    await activateKeepAwakeAsync(TAG);
  } catch (err) {
    /**
     * ЗАПИСЫВАЕМ, А НЕ ГЛОТАЕМ.
     *
     * Промах здесь не должен ронять экран, поэтому он и не бросается
     * дальше. Но до 1.5.57 он ещё и не оставлял следа — а жалоба «экран
     * гаснет» приходит с чужого телефона, где ни отладчика, ни logcat нет.
     * Единственный способ отличить «настройка выключена» от «блокировка не
     * встала» — вот эта строчка в журнале приложения.
     */
    driverLogger.warn('Не удалось удержать экран включённым', {
      action: 'keep_screen_on_failed',
      extra: { reason, error: err instanceof Error ? err.message : String(err) },
    });
  }
}

export function useKeepScreenOn(): void {
  const enabled = useSettingsStore((s) => s.keepScreenOn);

  useEffect(() => {
    if (!enabled) {
      driverLogger.info('Экран гасить разрешено — так задано в настройках', {
        action: 'keep_screen_on_disabled',
      });
      void deactivateKeepAwake(TAG).catch(() => {});
      return;
    }

    void reassertLock('mount');

    // Возврат на передний план — единственный надёжный момент, когда видно,
    // что Activity могла смениться. Слушателя ставим всегда, пока настройка
    // включена: проверка дешёвая, а пропущенное пересоздание стоит водителю
    // гаснущего экрана до перезапуска приложения.
    const sub = AppState.addEventListener('change', (state) => {
      if (state === 'active') void reassertLock('foreground');
    });

    return () => {
      sub.remove();
      void deactivateKeepAwake(TAG).catch(() => {});
    };
  }, [enabled]);
}
