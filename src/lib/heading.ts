/**
 * @file: src/lib/heading.ts
 * @description:
 *   Куда смотрит стрелка водителя на карте.
 *
 *   ПОЧЕМУ НЕ `coords.heading` ИЗ ТЕЛЕФОНА. Курс от GPS-приёмника выглядит
 *   готовым ответом и им не является: на серверной записи трека из 356 точек
 *   он принимал ВСЕГО ДВА различных значения — на малых скоростях приёмник
 *   его просто не считает, а на стоянке отдаёт последний известный. Стрелка
 *   с таким источником смотрит мимо дороги, и это ровно тот дефект, который
 *   разбирали в админке (v1.99.84).
 *
 *   ОТКУДА БЕРЁМ. Из ГЕОМЕТРИИ: направление отрезка, по которому водитель
 *   едет. Лучший источник — линия маршрута с сервера: она построена по
 *   дорогам, начинается в точке водителя, и её первый отрезок и есть «куда
 *   ехать». Если маршрута нет — считаем по двум последним координатам
 *   самого водителя.
 *
 *   ПОРОГ РАССТОЯНИЯ ОБЯЗАТЕЛЕН. Две точки в полуметре друг от друга дают
 *   случайный угол: это шум приёмника, а не поворот машины. Поэтому берём
 *   не «следующую точку», а первую, отстоящую хотя бы на `MIN_SPAN_M`.
 *
 * @dependencies: нет (чистые функции)
 * @created: 2026-09-07 (1.5.38)
 * @updated: 2026-09-09 (1.5.51 — порог скорости, база 15 м, предел поворота, отсев встречного курса)
 */

/** Точка, от которой можно считать направление. */
export interface HeadingPoint {
  latitude: number;
  longitude: number;
}

/**
 * Минимальная база для расчёта угла, в метрах.
 *
 * 15 м, а НЕ 5 (было до 1.5.51). Пять метров — это длина машины, но НЕ
 * больше погрешности городского фикса: типичный разброс 5-15 м даже в
 * движении. База, сравнимая с ошибкой, даёт угол, целиком собранный из
 * шума: на стоянке и в пробке стрелка разворачивалась на 180° при том, что
 * машина ехала прямо. Именно на это пожаловался владелец 09.09.2026.
 *
 * Пятнадцать метров — 0.9 секунды на 60 км/ч и 2.7 на 20 км/ч: угол
 * обновляется достаточно часто, чтобы поворот был виден вовремя, но
 * основание уже вдвое длиннее ошибки.
 */
export const MIN_SPAN_M = 15;

/**
 * Скорость, ниже которой направление НЕ пересчитывается вовсе, м/с.
 *
 * 1.4 м/с — это 5 км/ч, шаг пешехода. Стоящая машина всё равно «ползёт» по
 * координатам: приёмник шумит, и за минуту на светофоре набегает больше
 * пятнадцати метров случайного блуждания — порога расстояния мало, нужен
 * ещё и порог скорости. Стоящая машина смотрит туда же, куда ехала: так
 * ведёт себя любой навигатор.
 *
 * Отрицательная скорость (`-1`) означает «приёмник не знает» — тогда
 * решает только расстояние.
 */
export const MIN_SPEED_MPS = 1.4;

/**
 * Насколько градусов стрелка может повернуться за один фикс.
 *
 * Машина не разворачивается мгновенно: на секундном такте даже резкий
 * поворот во двор — это градусов сорок. Всё, что больше, — либо ошибка
 * приёмника, либо проекция на встречный отрезок дороги. Ограничение не
 * прячет настоящий разворот, а растягивает его на два-три кадра, зато
 * убирает мгновенные скачки на 180°.
 */
export const MAX_TURN_PER_FIX_DEG = 45;

const EARTH_RADIUS_M = 6_371_000;

function toRadians(deg: number): number {
  return (deg * Math.PI) / 180;
}

/** Расстояние между точками по большому кругу, в метрах. */
export function distanceMeters(from: HeadingPoint, to: HeadingPoint): number {
  const dLat = toRadians(to.latitude - from.latitude);
  const dLng = toRadians(to.longitude - from.longitude);
  const lat1 = toRadians(from.latitude);
  const lat2 = toRadians(to.latitude);

  const a =
    Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_RADIUS_M * Math.asin(Math.min(1, Math.sqrt(a)));
}

/**
 * Азимут от точки к точке: 0° — на север, 90° — на восток.
 *
 * Результат всегда в [0, 360): именно в такой шкале его ждёт `rotation`
 * маркера, и отрицательный угол там читался бы как поворот в другую сторону.
 */
export function bearingDegrees(from: HeadingPoint, to: HeadingPoint): number {
  const lat1 = toRadians(from.latitude);
  const lat2 = toRadians(to.latitude);
  const dLng = toRadians(to.longitude - from.longitude);

  const y = Math.sin(dLng) * Math.cos(lat2);
  const x = Math.cos(lat1) * Math.sin(lat2) - Math.sin(lat1) * Math.cos(lat2) * Math.cos(dLng);

  return ((Math.atan2(y, x) * 180) / Math.PI + 360) % 360;
}

/**
 * Направление в начале ломаной — куда ехать из первой точки.
 *
 * Идём вперёд до первой точки, отстоящей не меньше чем на `minSpanMeters`:
 * ломаная маршрута сгущается на поворотах, и соседняя точка там бывает в
 * метре, а угол по ней — это угол шума, а не дороги.
 *
 * `null` — направление неизвестно (точек мало или все они в одном месте).
 * Именно `null`, а не 0: ноль означал бы «на север», и стрелка уверенно
 * смотрела бы не туда вместо того, чтобы сохранить прежний угол.
 */
export function headingAlong(
  points: readonly HeadingPoint[],
  minSpanMeters: number = MIN_SPAN_M,
): number | null {
  const anchor = points[0];
  if (!anchor) return null;

  for (let i = 1; i < points.length; i++) {
    const next = points[i]!;
    if (distanceMeters(anchor, next) >= minSpanMeters) {
      return bearingDegrees(anchor, next);
    }
  }
  return null;
}

/**
 * Разница между углами по кратчайшей дуге, в градусах: (-180, 180].
 *
 * Через дугу, а не вычитанием: 350° и 10° отличаются на двадцать градусов,
 * а не на триста сорок, и наивная разность развернула бы стрелку в другую
 * сторону при каждом переходе через север.
 */
export function angleDelta(from: number, to: number): number {
  return ((((to - from) % 360) + 540) % 360) - 180;
}

/**
 * Куда повернуть стрелку, чтобы она не прыгала.
 *
 * @param current   текущий угол стрелки; `null` — стрелка ещё никуда не смотрит
 * @param candidate угол, который посчитала геометрия
 * @param maxTurn   предел поворота за один фикс
 *
 * Первый угол принимается как есть: ограничивать нечего, а стрелка,
 * доезжающая до правильного направления за пять кадров, выглядит сломанной.
 */
export function limitTurn(
  current: number | null,
  candidate: number,
  maxTurn: number = MAX_TURN_PER_FIX_DEG,
): number {
  if (current == null) return candidate;
  const delta = angleDelta(current, candidate);
  if (Math.abs(delta) <= maxTurn) return candidate;
  return (current + Math.sign(delta) * maxTurn + 360) % 360;
}

/**
 * Годится ли курс отрезка маршрута как направление стрелки.
 *
 * ЗАЧЕМ. Стрелку разворачивает проекция на маршрут: она даёт курс того
 * куска дороги, к которому машина оказалась ближе всего. На двусторонней
 * улице, на развязке и на устаревшей линии этот кусок бывает ВСТРЕЧНЫМ — и
 * стрелка честно показывает назад, пока водитель едет вперёд.
 *
 * Собственное перемещение водителя врать так не умеет: оно измерено, а не
 * выбрано. Поэтому оно и решает, доверять ли проекции.
 *
 * `movement === null` — перемещения ещё нет (машина только тронулась):
 * проверять нечем, проекции верим.
 */
export function isSnapBearingSane(
  snapBearing: number,
  movement: number | null,
  maxDeviationDeg = 120,
): boolean {
  if (movement == null) return true;
  return Math.abs(angleDelta(movement, snapBearing)) <= maxDeviationDeg;
}
