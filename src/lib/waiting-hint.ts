/**
 * @file: src/lib/waiting-hint.ts
 * @description:
 *   Что написать водителю про ожидание — одной строкой и по-человечески.
 *
 *   ЗАЧЕМ. Счётчик ожидания на подаче включается САМ, и до 1.5.47 водитель
 *   видел только растущее время. На четыре вопроса, которые у него возникают
 *   первыми, ответа на экране не было: сколько я жду, сколько ещё бесплатно,
 *   когда пойдут деньги и по какой цене. Ровно на этом начинается спор с
 *   клиентом — и водитель в нём безоружен.
 *
 *   1.5.48: ВРЕМЯ ПОКАЗЫВАЕТСЯ ВСЕГДА. До этого строка говорила ЛИБО про
 *   остаток бесплатного, ЛИБО про начисленную сумму, и «сколько я уже жду»
 *   на экране пропадало ровно в тот момент, когда пошли деньги — то есть
 *   когда этот вопрос и задают. Теперь время слева, деньги справа.
 *
 *   ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ С ТЕСТАМИ. Это текст про ДЕНЬГИ. Ошибка здесь
 *   не падает и не видна в логе: водитель просто говорит клиенту неверную
 *   сумму или неверный остаток бесплатного времени. Правила («пока идёт
 *   бесплатное — показываем остаток», «как только пошло платное — показываем
 *   начисленное») проверяются тестами, а не глазами на эмуляторе.
 *
 *   ПОЧЕМУ НЕ СЧИТАЕМ ДЕНЬГИ ЗДЕСЬ. Сумму присылает сервер: тариф на
 *   телефоне подставной, и посчитанное тут разошлось бы со списанием.
 *   Модуль только выбирает, ЧТО сказать, и форматирует.
 *
 * @dependencies: нет (чистые функции)
 * @created: 2026-09-09 (1.5.47)
 */

/** Состояние ожидания, как его присылает сервер. */
export interface WaitingState {
  /** Накоплено ожидания всего, секунды (включая идущее сейчас). */
  waitingSec: number;
  /** Идёт ли счётчик прямо сейчас. */
  waitingOn: boolean;
  /** Сколько ожидания бесплатно по тарифу, секунды. */
  freeSec: number;
  /** Цена минуты платного ожидания. */
  perMinute: number;
  /** Сколько уже начислено за ожидание, рубли. */
  cost: number;
}

/** Короткая подсказка для плашки над картой: текст и признак «уже платно». */
export interface WaitingHint {
  text: string;
  paid: boolean;
}

/** Секунды → «М:СС». Часы в ожидании не бывают, а если бывают — минуты растут. */
export function formatWaitClock(totalSec: number): string {
  const sec = Math.max(0, Math.floor(totalSec));
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  return `${m}:${String(s).padStart(2, '0')}`;
}

/** Рубли без копеек: на кнопке и в шапке дробная часть только мешает. */
function money(value: number): string {
  return `${Math.round(value)} ₽`;
}

/**
 * Что показать про ИДУЩЕЕ ожидание одной строкой.
 *
 * `null` — счётчик стоит: строке нечего занимать место.
 *
 * ПОЧЕМУ ТОЛЬКО ПОКА ИДЁТ. Строка живёт на плашке поверх карты, а в поездке
 * ожидание включают редко («подождите, я в аптеку»). Постоянная строка под
 * него была бы платой местом за событие, которого обычно нет. Накопленное
 * при этом не пропадает: оно входит в сумму на той же плашке, а разбор —
 * «сколько всего, сколько платно, на сколько рублей» — лежит в развёрнутой
 * шторке, куда за ним и лезут, когда клиент спорит.
 *
 * Время идёт первым и НИКОГДА не пропадает: это единственное число, которое
 * водитель называет клиенту дословно («я вас двенадцать минут жду»), и без
 * него сумма выглядит взятой с потолка. Второй частью идёт то, что важно
 * прямо сейчас: пока бесплатное не кончилось — сколько его осталось, после
 * — сколько уже начислено.
 *
 * СЛОВ «ПЛАТНО» И «БЕСПЛАТНО» ЗДЕСЬ НЕТ, и это не экономия ради экономии.
 * Строка живёт в чипе поверх карты, рядом с чипом «Итого», и вместе они
 * обязаны умещаться в ОДНУ строку: перенос при развёрнутой шторке уводит
 * нижний чип под её край (поймано на эмуляторе 1.5.48 — «14:41 · платно
 * 58 ₽» не влезло). Смысл при этом не теряется: платное ожидание чип
 * заливает предупреждающим цветом и показывает рубли, бесплатное — спокоен
 * и показывает остаток времени. Слова повторяли бы то, что уже сказано
 * цветом и единицами.
 */
export function waitingHint(state: WaitingState): WaitingHint | null {
  if (!state.waitingOn) return null;
  const waited = Math.max(0, Math.floor(state.waitingSec));

  const clock = formatWaitClock(waited);
  const free = Math.max(0, Math.floor(state.freeSec));
  const leftFree = free - waited;

  // Ожидание в этом тарифе бесплатное всегда — обещать «платно» нельзя, и
  // говорить об остатке бесплатного тоже: он бесконечный.
  if (state.perMinute <= 0) {
    return { text: clock, paid: false };
  }

  if (leftFree > 0) {
    // Пока идёт бесплатное, водителю важен ОСТАТОК: он решает, звонить ли
    // клиенту и стоит ли ждать дальше.
    return { text: `${clock} · ещё ${formatWaitClock(leftFree)}`, paid: false };
  }

  // Бесплатное кончилось: рядом со временем встают деньги.
  return { text: `${clock} · ${money(state.cost)}`, paid: true };
}

/**
 * Секунды ожидания «на сейчас» — серверные плюс прошедшие с момента ответа.
 *
 * ЗАЧЕМ. Сервер опрашивается раз в десять секунд, и таймер, показанный
 * прямо из ответа, стоял бы по десять секунд и прыгал через десять — на
 * экране это выглядит сломанным. Отсчитывать же время целиком на телефоне
 * нельзя: до 1.5.48 так и было, и счёт начинался заново при каждом
 * возвращении на экран, а ожидание, включённое в поездке, не считалось
 * вовсе.
 *
 * Деньги здесь по-прежнему НЕ пересчитываются: между ответами сервера сумма
 * стоит, и это честно — начисляет её он.
 */
export function liveWaitingSec(
  waitingSec: number,
  waitingOn: boolean,
  sinceFetchMs: number,
): number {
  const base = Math.max(0, Math.floor(waitingSec));
  if (!waitingOn) return base;
  return base + Math.floor(Math.max(0, sinceFetchMs) / 1000);
}

/**
 * Условия ожидания одной строкой — для расшифровки в развёрнутой шторке.
 *
 * `null` — в тарифе ожидание не тарифицируется, и обещать нечего.
 */
export function waitingTermsText(freeSec: number, perMinute: number): string | null {
  if (perMinute <= 0) return null;
  const freeMin = Math.round(Math.max(0, freeSec) / 60);
  const rate = `${Math.round(perMinute)} ₽/мин`;
  if (freeMin <= 0) return `Ожидание платное с первой минуты · ${rate}`;
  return `Бесплатно ${freeMin} мин, дальше ${rate}`;
}
