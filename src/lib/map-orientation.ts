/**
 * @file: src/lib/map-orientation.ts
 * @description:
 *   Ориентация карты заказа: север сверху или по курсу.
 *
 *   ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Поворот карты ломает стрелку водителя, и это
 *   не мелочь: до 1.5.42 карта была жёстко «севером вверх» ИМЕННО поэтому —
 *   маркер рисуется в экранных координатах и о повороте карты не знает, так
 *   что на повёрнутой карте стрелка показывала бы не туда. Правило здесь и
 *   покрыто тестами, потому что ошибка в нём выглядит не как поломка, а как
 *   «стрелка врёт», — водитель поверит стрелке и повернёт не туда.
 *
 *   ГДЕ ИМЕННО ПРИМЕНЯЕТСЯ УГОЛ СТРЕЛКИ. Не внутри SVG, а в НАТИВНОМ
 *   пропе `rotation` у маркера. Разница не косметическая: разметку маркера
 *   Android держит растром и обновляет, только пока открыто окно
 *   `tracksViewChanges`, — а угол меняется когда угодно. 08.09.2026 это
 *   поймано на эмуляторе: числа на экране показывали курс 327, камеру 327
 *   и стрелку 0, то есть арифметика была верна, а нарисованная стрелка
 *   осталась повёрнутой на прежние 327°. Нативный поворот растра не
 *   касается и потому не устаревает.
 *
 *   ПОЧЕМУ НЕ `flat`. У плоского маркера Google считает `rotation` от
 *   севера КАРТЫ, и компенсация не понадобилась бы вовсе. Проверено на
 *   том же эмуляторе — не работает: маркер со своей разметкой остаётся
 *   билбордом, и угол по-прежнему экранный. Поэтому компенсируем сами.
 *
 *   ТРИ ПРАВИЛА, КОТОРЫЕ ЗДЕСЬ ЖИВУТ.
 *   • Угол стрелки на экране = курс МИНУС поворот камеры. В режиме «по
 *     курсу» это ноль — стрелка всегда смотрит вверх, как в навигаторе; в
 *     режиме «север сверху» это сам курс. Одна формула на оба режима.
 *   • Камера доворачивается не на каждый градус, а с порогом: курс шумит, и
 *     без порога карта мелко трясётся на каждом фиксе GPS.
 *   • Разница углов считается по КРАТЧАЙШЕЙ дуге: между 350° и 10° двадцать
 *     градусов, а не триста сорок. Иначе на переходе через север карта
 *     разворачивалась бы через полный круг.
 *
 * @dependencies: нет
 * @created: 2026-09-08 (1.5.42)
 */

/** Как водитель видит карту. */
export type MapOrientation = 'course' | 'north';

/**
 * На сколько градусов должен разойтись курс с камерой, чтобы её доворачивать.
 *
 * 8° — заметный поворот руля, но выше обычного дрожания курса на прямой.
 * Меньше — карта дёргается на месте, больше — поворот запаздывает и водитель
 * успевает увидеть карту «боком» в повороте.
 */
export const TURN_THRESHOLD_DEG = 8;

/**
 * Сколько метров должен проехать водитель, чтобы карта вернулась к режиму
 * «по курсу» после кнопки общего плана.
 *
 * Кнопка «показать весь маршрут» разворачивает карту севером вверх: обзорный
 * план на повёрнутой карте нечитаем — это и есть та потеря ориентации, ради
 * которой её вообще смотрят. Возвращать поворот сразу нельзя, иначе кнопка
 * бесполезна; ждать поворота руля — тоже, водитель может ехать прямо. Ждём
 * ровно того, что он поехал дальше.
 */
export const RESUME_COURSE_UP_M = 30;

/** Привести угол к [0, 360). */
export function normalizeAngle(deg: number): number {
  if (!Number.isFinite(deg)) return 0;
  return ((deg % 360) + 360) % 360;
}

/**
 * Кратчайшая разница углов, в диапазоне (-180, 180].
 *
 * Положительная — `to` правее `from` по часовой стрелке.
 */
export function angleDelta(from: number, to: number): number {
  const diff = normalizeAngle(to) - normalizeAngle(from);
  if (diff > 180) return diff - 360;
  if (diff <= -180) return diff + 360;
  return diff;
}

/** Пора ли доворачивать камеру под курс. */
export function shouldTurnCamera(
  cameraHeading: number,
  course: number | null,
  thresholdDeg: number = TURN_THRESHOLD_DEG,
): boolean {
  if (course == null || !Number.isFinite(course)) return false;
  return Math.abs(angleDelta(cameraHeading, course)) >= thresholdDeg;
}

/**
 * Под каким углом рисовать стрелку водителя НА ЭКРАНЕ.
 *
 * Маркер со своей разметкой — билборд: он не поворачивается вместе с
 * картой, а всегда смотрит в камеру. Значит поворот карты надо вычесть из
 * курса руками.
 */
export function screenHeading(course: number, cameraHeading: number): number {
  return normalizeAngle(course - cameraHeading);
}

/** Куда должна смотреть камера при этом режиме и курсе. */
export function targetCameraHeading(
  orientation: MapOrientation,
  course: number | null,
): number {
  if (orientation !== 'course' || course == null || !Number.isFinite(course)) return 0;
  return normalizeAngle(course);
}
