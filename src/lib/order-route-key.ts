/**
 * @file: src/lib/order-route-key.ts
 * @description:
 *   Ключ запроса линии маршрута и правило «прежняя линия ещё годится».
 *
 *   ПОЧЕМУ ВМЕСТЕ. Правило читает ключ по позициям, а собирает ключ другой
 *   код. Разъедься они — правило молча начнёт сравнивать не те поля и станет
 *   всегда возвращать `false` (лишние запросы) или всегда `true` (чужая линия
 *   на карте). Ни то, ни другое не падает и не видно в типах, поэтому оба
 *   живут в одном файле и проверяются одними тестами.
 *
 *   ЗАЧЕМ ОГРУБЛЯЕТСЯ КООРДИНАТА. Позиция приходит раз в несколько секунд, и
 *   запрашивать маршрут на каждую точку — двенадцать обращений в минуту на
 *   водителя ради линии, которая за это время не меняется. Три знака ≈ 60–110
 *   метров: пока водитель не проехал этот шаг, ключ прежний и react-query
 *   отдаёт готовый ответ. Тем же приёмом это решено на карте диспетчера
 *   (v1.99.52).
 *
 *   ЗАЧЕМ В КЛЮЧЕ СТАТУС. Цель зависит от стадии: до посадки ведём к клиенту,
 *   после — к точке назначения. Без статуса в ключе линия осталась бы вести к
 *   клиенту, которого водитель уже везёт.
 *
 * @dependencies: нет
 * @created: 2026-09-07 (1.5.39)
 */

/** Шаг огрубления координат в ключе запроса: 3 знака ≈ 60–110 м. */
export const KEY_PRECISION = 3;

export interface OrderRouteKeyParams {
  orderId: string | null | undefined;
  status: string | null | undefined;
  lat: number | null | undefined;
  lng: number | null | undefined;
}

/** Ключ react-query для линии маршрута заказа. */
export function orderRouteKey({ orderId, status, lat, lng }: OrderRouteKeyParams): unknown[] {
  return [
    'order-route',
    orderId,
    status,
    lat != null ? lat.toFixed(KEY_PRECISION) : null,
    lng != null ? lng.toFixed(KEY_PRECISION) : null,
  ];
}

/**
 * Годится ли прежняя линия как заглушка на время нового запроса.
 *
 * Ключ меняется от трёх вещей, и безобидна только одна. Сдвинулся водитель —
 * линия почти та же, и показывать прежнюю правильно: моргание маршрута
 * раздражает сильнее лёгкой неактуальности. Но сменился заказ (переключение
 * «Текущий / Встречный» на одной и той же карте) или статус (клиент сел в
 * машину, цель стала точкой назначения) — прежняя линия ведёт НЕ ТУДА.
 *
 * До 1.5.39 это было косметикой: чужая линия висела рядом полсекунды. С
 * 1.5.39 машина притягивается к линии — то есть встала бы на чужой маршрут и
 * развернулась вдоль него, а это уже прямая дезинформация.
 */
export function isSameRouteTarget(
  previousKey: readonly unknown[] | undefined,
  orderId: string | null | undefined,
  status: string | null | undefined,
): boolean {
  if (!previousKey) return false;
  return previousKey[1] === orderId && previousKey[2] === status;
}
