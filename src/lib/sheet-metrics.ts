/**
 * @file: src/lib/sheet-metrics.ts
 * @description:
 *   Размеры шторки на экране заказа.
 *
 *   ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Эта арифметика ломалась дважды подряд, и оба
 *   раза — молча, потому что проверить её можно было только глазами на
 *   эмуляторе. В 1.5.23 высота считалась от ОКНА, и верх развёрнутой шторки
 *   заезжал под шапку вместе с полоской-хватом. В 1.5.24 её починили через
 *   замер контейнера, но добавили потолок в 66% — и шторка перестала
 *   доходить до верха вовсе. Здесь она обложена тестами.
 *
 * @dependencies: нет (чистая арифметика)
 * @created: 2026-09-03 (v1.5.25)
 */

/**
 * Свёрнутая шторка: полоса этапов и текущая цель с кнопками.
 *
 * Замерено на эмуляторе 360dp (1.5.23): адрес в ОДНУ строку вместе с чипом
 * подъезда занимает 159, при 170 он влезал впритык. Длинные адреса
 * («Красноярск, ул. Академика Киренского, д. 32, корп. 1») переносятся на
 * вторую строку — это ещё ~34, и чип подъезда уезжал под обрез. Подъезд
 * терять нельзя: водитель без него звонит клиенту и спрашивает.
 */
export const SHEET_COLLAPSED = 215;

/**
 * Полоска карты над развёрнутой шторкой.
 *
 * Ровно столько, чтобы не ушли под шторку плавающие чипы — номер заказа и
 * таймер ожидания: они начинаются в 12 от верха и высотой около 30. Больше
 * тут держать нечего: водитель тянет шторку вверх ЗА подробностями, и
 * карта в этот момент ему не нужна — за ней он шторку и опустит.
 *
 * Было 96 плюс потолок в 66% высоты: два ограничения на одно решение, и
 * вместе они не давали шторке дойти до верха.
 */
export const MAP_MIN_VISIBLE = 56;

/**
 * Высота развёрнутой шторки.
 *
 * СЧИТАЕТСЯ ОТ ИЗМЕРЕННОГО КОНТЕЙНЕРА, А НЕ ОТ ОКНА: шторка живёт не в
 * окне — над ней шапка со статусом и полоса с балансом, под ней вкладки.
 *
 * `containerHeight = 0` — разметка ещё не посчиталась; отдаём свёрнутую
 * высоту, чтобы на первом кадре шторка не прыгала.
 */
export function sheetExpandedHeight(
  containerHeight: number,
  actionBarHeight: number,
): number {
  if (containerHeight <= 0) return SHEET_COLLAPSED;
  const available = containerHeight - actionBarHeight - MAP_MIN_VISIBLE;
  return Math.max(SHEET_COLLAPSED, available);
}
