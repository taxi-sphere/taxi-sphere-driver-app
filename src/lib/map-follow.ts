/**
 * @file: src/lib/map-follow.ts
 * @description:
 *   Слежение камеры за машиной: когда карта ведёт водителя, а когда
 *   принадлежит ему.
 *
 *   ЗАЧЕМ. До 1.5.45 камера двигалась ровно дважды за поездку — на открытии
 *   заказа и на смене стадии (`map-fit`). Дальше водитель ехал, а карта
 *   стояла: стрелка молча уползала за край экрана. Тот же корень был у двух
 *   других жалоб, которые выглядели самостоятельными: поворот камеры идёт
 *   вокруг ЦЕНТРА КАРТЫ, и чем дальше от него машина, тем шире дуга, по
 *   которой доворот выбрасывает стрелку с экрана.
 *
 *   ПРАВИЛО ВОЗВРАТА — ВРЕМЯ *И* РАССТОЯНИЕ, А НЕ ОДНО ИЗ ДВУХ. Водитель
 *   должен иметь право отодвинуть карту и посмотреть, что впереди; значит
 *   любой его жест слежение выключает. Включать обратно только по таймеру
 *   нельзя: водитель, стоящий у подъезда клиента и разглядывающий двор,
 *   получил бы карту, выдернутую из-под пальца. Только по расстоянию — тоже
 *   нельзя: тогда достаточно тронуться, и карта прыгнет посреди жеста.
 *   Поэтому оба условия сразу: прошло время И машина проехала. Стоящая
 *   машина не проезжает ничего, поэтому её карта остаётся там, куда её
 *   поставили, сколько угодно долго.
 *
 *   ЭТО ЖЕ ПРАВИЛО ЗАМЕНИЛО `RESUME_COURSE_UP_M` ИЗ 1.5.42. Кнопка «весь
 *   маршрут» решала ту же задачу своим механизмом — «вернуть поворот, когда
 *   водитель проехал 30 м». Две системы для одного вопроса «чья сейчас
 *   камера» неизбежно разъезжаются: кнопка возвращала поворот, но не центр,
 *   и общий план после неё жил вечно. Теперь кнопка — такой же перехват, как
 *   жест пальцем, и возвращается всё одновременно.
 *
 *   ПОЧЕМУ ДЛИТЕЛЬНОСТЬ АНИМАЦИИ БЕРЁТСЯ ИЗ НАБЛЮДАЕМОГО ИНТЕРВАЛА. Плавность
 *   движения на карте даёт не частота GPS, а то, что следующая анимация
 *   начинается раньше, чем закончилась предыдущая. Возьмём длительность ровно
 *   в интервал — и любой опоздавший фикс оставит карту стоять на разницу;
 *   именно так набирается «рывками», на которые жалуется водитель. Поэтому
 *   длительность берётся с запасом (`FOLLOW_LEAD`) от СГЛАЖЕННОГО интервала:
 *   карта всегда чуть-чуть не доезжает до последней точки и потому не
 *   останавливается никогда. Тот же приём, что у буфера на карте диспетчера
 *   (`gps-jitter-buffer.ts`, сервер v1.99.55), но здесь он умещается в две
 *   функции: свой GPS приходит ровно, сглаживать сетевой джиттер не нужно.
 *
 * @dependencies: @/lib/heading (distanceMeters — тот же расчёт, что у курса)
 * @created: 2026-09-08 (1.5.45)
 */

import { distanceMeters, type HeadingPoint } from './heading';

/** Точка на карте — ровно то, что нужно правилу возврата. */
export type FollowPoint = HeadingPoint;

/**
 * Сколько ждать после того, как водитель тронул карту.
 *
 * 12 секунд — заметно дольше любого осмысленного жеста (отодвинуть, глянуть,
 * отпустить) и заметно короче, чем время, за которое водитель успеет забыть,
 * что карта отпущена. Меньше — карта дёргается из-под руки; больше — водитель
 * в повороте едет по неподвижной карте.
 */
export const FOLLOW_RESUME_MS = 12_000;

/**
 * Сколько метров должна проехать машина, чтобы карта вернулась к ней.
 *
 * 30 м — это уже точно движение, а не дрожание приёмника у стоящей машины
 * (то же число, что было у `RESUME_COURSE_UP_M` в 1.5.42, и по той же
 * причине). На 40 км/ч проезжается за три секунды, то есть решает всегда
 * время, а не расстояние; расстояние работает только в одну сторону — держит
 * карту у стоящего.
 */
export const FOLLOW_RESUME_M = 30;

/** Момент, когда водитель забрал карту себе. */
export interface FollowInterrupt {
  /** Время жеста, `Date.now()`. */
  at: number;
  /**
   * Где была машина в этот момент. `null` — позиции ещё не знали, и тогда
   * условие расстояния проверять не по чему.
   */
  from: FollowPoint | null;
}

/** Пора ли возвращать камеру к машине. */
export function shouldResumeFollow(
  interrupt: FollowInterrupt | null,
  now: number,
  here: FollowPoint | null,
  options?: { afterMs?: number; afterMeters?: number },
): boolean {
  // Перехвата не было — ждать нечего. Возвращаем «да», чтобы состояние
  // «слежение выключено без причины» не могло залипнуть навсегда.
  if (!interrupt) return true;

  const afterMs = options?.afterMs ?? FOLLOW_RESUME_MS;
  const afterMeters = options?.afterMeters ?? FOLLOW_RESUME_M;

  const elapsed = now - interrupt.at;
  // Часы ушли назад — считаем, что время прошло: залипшее слежение хуже
  // раннего возврата.
  if (Number.isFinite(elapsed) && elapsed >= 0 && elapsed < afterMs) return false;

  // Не знали, где машина была, — расстояние проверять не по чему.
  if (!interrupt.from) return true;
  // Не знаем, где машина сейчас, — возвращать не к чему.
  if (!here) return false;

  return distanceMeters(interrupt.from, here) >= afterMeters;
}

/* ─── Длительность анимации камеры ──────────────────────────────────────── */

/** Насколько анимация длиннее наблюдаемого интервала между фиксами. */
export const FOLLOW_LEAD = 1.3;

/** Границы длительности: короче — рвано, длиннее — карта заметно отстаёт. */
export const FOLLOW_MIN_MS = 600;
export const FOLLOW_MAX_MS = 2500;

/** Чем считать интервал, пока не пришло ни одного второго фикса. */
export const FOLLOW_DEFAULT_INTERVAL_MS = 1000;

/**
 * Вес нового замера в скользящем среднем интервала.
 *
 * Четверть — среднее «помнит» примерно четыре последних интервала: реакция
 * на смену условий (город → трасса) есть, а на один опоздавший пакет среднее
 * не прыгает.
 */
export const INTERVAL_EMA_ALPHA = 0.25;

/**
 * Замеры вне этих границ в среднее не идут: короче — двойной фикс от
 * приёмника, длиннее — потеря сигнала (двор, тоннель), а не темп съёмки.
 */
const SAMPLE_MIN_MS = 250;
const SAMPLE_MAX_MS = 5000;

/** Обновить сглаженный интервал между фиксами. */
export function blendInterval(prev: number | null, sampleMs: number): number {
  if (!Number.isFinite(sampleMs)) return prev ?? FOLLOW_DEFAULT_INTERVAL_MS;
  const sample = Math.min(Math.max(sampleMs, SAMPLE_MIN_MS), SAMPLE_MAX_MS);
  if (prev == null || !Number.isFinite(prev)) return sample;
  return prev + (sample - prev) * INTERVAL_EMA_ALPHA;
}

/** Сколько должна длиться анимация камеры при таком интервале фиксов. */
export function followCameraDuration(intervalMs: number | null): number {
  const base =
    intervalMs != null && Number.isFinite(intervalMs) && intervalMs > 0
      ? intervalMs
      : FOLLOW_DEFAULT_INTERVAL_MS;
  return Math.round(Math.min(Math.max(base * FOLLOW_LEAD, FOLLOW_MIN_MS), FOLLOW_MAX_MS));
}
