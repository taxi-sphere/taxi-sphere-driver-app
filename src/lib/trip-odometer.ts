/**
 * @file: src/lib/trip-odometer.ts
 * @description:
 *   Одометр поездки: из потока точек GPS — пройденные метры и секунды
 *   В ДВИЖЕНИИ.
 *
 *   ЗАЧЕМ. Сервер не знает, сколько машина проехала: маршрут может не
 *   совпасть с планом, а плана может не быть вовсе — клиент вправе не
 *   назвать конечную точку. Мерить может только телефон. Считать по этим
 *   метрам ДЕНЬГИ телефон не должен (тариф здесь подставной, и число на
 *   экране разошлось бы со списанием) — он шлёт факты, сумму считает сервер.
 *
 *   ПОЧЕМУ ВРЕМЯ СЧИТАЕТСЯ ПО ДВИЖЕНИЮ, А НЕ ПО ЧАСАМ. За минуту в пути
 *   тариф берёт цену минуты, за минуту стоянки — цену ожидания. Возьми
 *   время просто как «конец минус начало», и стоянка оплатится дважды:
 *   и как путь, и как ожидание. Поэтому секунды прибавляются ТОЛЬКО когда
 *   машина за этот отрезок реально сместилась.
 *
 *   ПОЧЕМУ ЕСТЬ ПОРОГ СМЕЩЕНИЯ. Стоящая машина «ползает» в пределах
 *   погрешности приёмника. Без порога такая машина за смену намотала бы
 *   километры, и водитель предъявил бы счёт за поездку, которой не было.
 *
 *   ПОЧЕМУ ФИКСАМ НЕ ВЕРЯТ НА СЛОВО. Когда небо закрыто, приёмник отдаёт
 *   положение по вышкам — водитель «прыгает» на сотни метров и обратно, и
 *   счётчик засчитал бы этот прыжок дважды. Отсюда две проверки: паспортная
 *   точность фикса и правдоподобие скорости. Притягивание к дорогам эту
 *   задачу не решает: оно требует сети посреди поездки и ломается ровно
 *   там, где нужнее всего — на бездорожье, где дорог нет вовсе.
 *
 *   ПОЧЕМУ ЕСТЬ ПОТОЛОК ПРОМЕЖУТКА. Между двумя точками может пройти час:
 *   тоннель, подземная парковка, приложение выгрузила система. Расстояние
 *   между ними — правда (машина действительно там оказалась), а вот считать
 *   этот час временем в движении нельзя: водитель мог всё это время стоять.
 *
 * @dependencies: @/lib/heading (distanceMeters — тот же расчёт, что у курса)
 * @created: 2026-09-09 (1.5.46)
 */

import { distanceMeters, type HeadingPoint } from './heading';

/** Точка в потоке одометра. */
export interface OdometerPoint extends HeadingPoint {
  /** Время фикса, миллисекунды. */
  at: number;
  /**
   * Паспортная погрешность фикса, метры. `undefined` — приёмник не сказал.
   *
   * Главный признак вранья: когда небо закрыто (двор-колодец, парковка
   * торгового центра, тоннель), Android подставляет положение по вышкам и
   * честно помечает его точностью в сотни метров.
   */
  accuracy?: number;
}

/** Накопленное состояние одометра по одному заказу. */
export interface OdometerState {
  /** Пройденные метры. */
  distanceM: number;
  /** Секунды в движении. */
  movingSec: number;
  /** Последняя учтённая точка. `null` — поток ещё не начинался. */
  last: OdometerPoint | null;
}

/**
 * Меньше этого смещение считаем дрожанием приёмника, а не движением.
 *
 * 10 метров — примерно паспортная точность бытового GPS в городе. Меньше
 * порог — стоящая машина набирает пробег; больше — теряется медленное
 * движение в пробке, где шаг между фиксами и так короткий.
 */
export const MIN_STEP_M = 10;

/**
 * Промежуток длиннее этого во время в движении не идёт.
 *
 * Полторы минуты: при секундном темпе съёмки это уже не «пропустили пару
 * фиксов», а провал связи или сон приложения.
 */
export const MAX_GAP_SEC = 90;

/**
 * Хуже этой погрешности фикс в пробег не идёт.
 *
 * ЗАЧЕМ. Это ровно тот случай, из-за которого счётчик врёт заметнее всего:
 * машина стоит во дворе-колодце, приёмник теряет небо и отдаёт положение по
 * вышкам — водитель «прыгает» на триста метров и обратно. Без этого порога
 * счётчик засчитал бы шестьсот метров за две секунды стоянки, и цена
 * поездки скакнула бы на ровном месте.
 *
 * 50 метров — граница между спутниковым фиксом (обычно 5–20 м) и положением по
 * вышкам (сотни). Тот же порог сервер применяет к точкам на карте.
 */
export const MAX_ACCURACY_M = 50;

/**
 * Быстрее этого машина не ездит — значит, фикс врёт.
 *
 * 55 м/с ≈ 200 км/ч: выше любой реальной скорости такси и заметно ниже
 * скорости «прыжка» (триста метров за секунду — это 1080 км/ч). Проверка
 * ловит враньё, которое приёмник НЕ пометил плохой точностью, а таких
 * фиксов хватает.
 *
 * Важно, что отрезок именно ОТБРАСЫВАЕТСЯ, а точка отсчёта остаётся
 * прежней: когда придёт нормальный фикс, настоящее перемещение зачтётся
 * один раз, а не дважды — туда и обратно.
 */
export const MAX_SPEED_MPS = 55;

/** Пустой одометр. */
export function emptyOdometer(): OdometerState {
  return { distanceM: 0, movingSec: 0, last: null };
}

/**
 * Учесть очередную точку.
 *
 * Возвращает НОВОЕ состояние — прежнее не меняется: так его можно спокойно
 * держать в сторе и сравнивать «до и после».
 */
export function accumulate(state: OdometerState, point: OdometerPoint): OdometerState {
  if (!Number.isFinite(point.latitude) || !Number.isFinite(point.longitude)) {
    return state;
  }

  // Фикс с плохой точностью не годится ни как конец отрезка, ни как его
  // начало: положение по вышкам врёт в обе стороны.
  if (point.accuracy != null && point.accuracy > MAX_ACCURACY_M) return state;

  const last = state.last;
  if (!last) return { ...state, last: point };

  // Точка из прошлого — обычно запоздавший пакет из фонового батча.
  // Двигать по ней одометр нельзя: расстояние посчиталось бы дважды.
  if (point.at <= last.at) return state;

  const step = distanceMeters(last, point);
  if (step < MIN_STEP_M) {
    // Машина стоит. Точку отсчёта НЕ сдвигаем: иначе медленное движение
    // рассыпалось бы на шаги ниже порога и не набрало бы ни метра.
    return state;
  }

  const gapSec = (point.at - last.at) / 1000;

  // Скачок, который приёмник не пометил плохой точностью. Отрезок
  // отбрасываем, точку отсчёта НЕ сдвигаем: настоящее перемещение зачтётся
  // следующим нормальным фиксом — один раз, а не туда и обратно.
  if (gapSec > 0 && step / gapSec > MAX_SPEED_MPS) return state;

  return {
    distanceM: state.distanceM + step,
    movingSec: state.movingSec + (gapSec <= MAX_GAP_SEC ? gapSec : 0),
    last: point,
  };
}

/** Показания в том виде, в каком их принимает сервер (целые). */
export function readingOf(state: OdometerState): { distanceM: number; movingSec: number } {
  return {
    distanceM: Math.round(state.distanceM),
    movingSec: Math.round(state.movingSec),
  };
}

/**
 * Стоит ли отправлять показания на сервер.
 *
 * Отправка идёт не на каждый фикс: секундный поток означал бы запрос в
 * секунду на каждого водителя. Шлём, когда накопилось заметное расстояние
 * ИЛИ прошло достаточно времени — второе нужно, чтобы стоящая в пробке
 * машина не выглядела на сервере пропавшей.
 */
export const PUSH_EVERY_M = 200;
export const PUSH_EVERY_MS = 30_000;

export function shouldPush(
  state: OdometerState,
  sent: { distanceM: number; atMs: number } | null,
  nowMs: number,
): boolean {
  const reading = readingOf(state);
  if (reading.distanceM <= 0 && reading.movingSec <= 0) return false;
  if (!sent) return true;
  if (reading.distanceM - sent.distanceM >= PUSH_EVERY_M) return true;
  return nowMs - sent.atMs >= PUSH_EVERY_MS;
}
