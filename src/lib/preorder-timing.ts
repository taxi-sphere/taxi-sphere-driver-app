/**
 * @file: src/lib/preorder-timing.ts
 * @description:
 *   Когда предзаказ в списке свободных считается текущим (1.5.60).
 *
 *   ЗАЧЕМ. Деление «Сейчас / Предзаказы» смотрело только на то, есть ли у
 *   заказа время подачи. Предзаказ на 14:00 висел в «Предзаказах» и в
 *   13:58, и в 14:10 — а сервер уже с 13:25 предлагал его водителям.
 *   Решение владельца от 13.09.2026: текущим предзаказ становится за
 *   «Lead time» минут до подачи — той же цифрой, по которой сервер начинает
 *   его раздавать. Цифру присылает сервер (v1.100.14) в `meta.preorderLeadMin`.
 *
 *   Старый сервер цифру не пришлёт — тогда текущим считается только
 *   предзаказ, время которого уже наступило: это честнее, чем прятать
 *   просроченный заказ в «Предзаказах».
 *
 *   Правило совпадает с `src/lib/preorder-timing.ts` сервера — репозитории
 *   раздельные, общего пакета пока нет.
 *
 * @dependencies: нет (чистые функции)
 * @created: 2026-09-13 (1.5.60)
 */

/**
 * Считать ли заказ текущим в момент `now`.
 *
 * @param scheduledAt время подачи, ISO; пусто — заказ на «сейчас»
 * @param leadTimeMin за сколько минут до подачи; нет — сервер старше v1.100.14
 * @param now текущее время в мс — параметром, чтобы функция была чистой
 */
export function isOrderCurrent(
  scheduledAt: string | null | undefined,
  leadTimeMin: number | null | undefined,
  now: number,
): boolean {
  if (!scheduledAt) return true;
  const at = Date.parse(scheduledAt);
  // Неразборчивое время: заказ всё же предзаказ, и объявлять его срочным
  // по ошибке в данных хуже, чем оставить в предзаказах.
  if (!Number.isFinite(at)) return false;
  const lead =
    typeof leadTimeMin === 'number' && Number.isFinite(leadTimeMin) ? Math.max(0, leadTimeMin) : 0;
  return at - lead * 60_000 <= now;
}
