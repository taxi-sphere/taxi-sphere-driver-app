/**
 * @file: src/lib/route-panel.ts
 * @description:
 *   Что делает нажатие в панели выбора пути и когда она прячется сама.
 *
 *   ЗАЧЕМ ОТДЕЛЬНО ОТ КОМПОНЕНТА. У панели три кнопки и несколько состояний,
 *   и одно и то же нажатие значит РАЗНОЕ: ткнуть в невыбранный вариант —
 *   выбрать его, ткнуть второй раз в тот же — свернуть ряд. Правило простое,
 *   но проверить его глазами можно только за рулём, а тестовой библиотеки
 *   для компонентов в проекте нет — здесь принято выносить решение в чистую
 *   функцию и проверять её (`route-choice`, `map-follow`, `sheet-metrics`).
 *
 *   СВОРАЧИВАЕТ ПОВТОРНОЕ НАЖАТИЕ ВОДИТЕЛЯ, А НЕ «НАЖАТИЕ НА АКТИВНУЮ»
 *   (1.5.58). Сначала было второе, и ряд закрывался посреди сравнения путей.
 *   Причина: активная кнопка меняется САМА, без участия водителя — как
 *   только опорная точка выбранного пути остаётся позади, `useOrderRoute`
 *   снимает её и возвращает в активные «быстрее». Водитель жмёт «быстрее»,
 *   чтобы переключиться, а для панели это «нажал на активную» — и ряд
 *   складывался. Поэтому считаем не подсветку, а то, что водитель сам нажал
 *   С МОМЕНТА РАСКРЫТИЯ ряда: первое нажатие после открытия всегда выбирает,
 *   что бы там ни было подсвечено.
 *
 *   ПОЧЕМУ НЕТ КРЕСТИКА. За рулём меньше целей — лучше, а «ткнуть ещё раз в
 *   то, что только что выбрал» — единственное нажатие, которому в этом ряду
 *   больше нечего было делать.
 *
 * @dependencies: нет (чистые функции)
 * @created: 2026-09-10 (1.5.57)
 * @updated: 2026-09-11 (1.5.58 — считаем нажатия водителя, а не подсветку)
 */

/** Куда нажали: в один из вариантов пути или в «Без маршрута». */
export type RoutePanelTarget =
  | { kind: 'variant'; index: number }
  | { kind: 'noRoute' };

/** Что из этого следует. */
export type RoutePanelAction =
  /** Построить этот вариант, ряд оставить открытым — водитель сравнивает. */
  | 'choose'
  /** Убрать линию с карты. */
  | 'hide'
  /** Свернуть ряд, оставив всё как есть. */
  | 'collapse';

/**
 * Через сколько ряд прячется сам.
 *
 * Водитель выбрал путь и поехал — дальше панель только занимает низ карты.
 * Пятнадцать секунд: хватает сравнить два варианта и не успевает надоесть.
 * Отсчёт сбрасывает ЛЮБОЕ нажатие, поэтому долгое сравнение ряд не закроет.
 */
export const ROUTE_PANEL_AUTOHIDE_MS = 15_000;

export interface RoutePanelState {
  /** Какой вариант ведёт сейчас; 0 — быстрый. */
  chosenIndex: number;
  /** Линия убрана с карты. */
  hidden: boolean;
}

/**
 * Ключ кнопки — им и запоминается «что водитель нажал».
 *
 * Строкой, а не объектом: сравнивать на равенство придётся на каждом
 * нажатии, а два `{kind, index}` равны только поэлементно.
 */
export function routePanelKey(target: RoutePanelTarget): string {
  return target.kind === 'noRoute' ? 'none' : `v${target.index}`;
}

/**
 * Активна ли кнопка — то есть описывает ли она то, что происходит сейчас.
 *
 * Это ТОЛЬКО подсветка. Решение о нажатии на неё не опирается: подсветка
 * меняется сама (см. шапку), а действие обязано зависеть только от того,
 * что делал водитель.
 *
 * Скрытая линия «главнее» выбранного варианта: выбор при этом сохранён, но
 * на карте его не видно, и подсветить вариант значило бы соврать.
 */
export function isRoutePanelTargetActive(
  target: RoutePanelTarget,
  state: RoutePanelState,
): boolean {
  if (target.kind === 'noRoute') return state.hidden;
  return !state.hidden && target.index === state.chosenIndex;
}

/**
 * Что сделать по нажатию.
 *
 * @param lastTapped ключ кнопки, которую водитель нажал последней с момента
 *   раскрытия ряда; `null` — ещё не нажимал ничего
 */
export function routePanelAction(
  target: RoutePanelTarget,
  lastTapped: string | null,
): RoutePanelAction {
  if (lastTapped !== null && routePanelKey(target) === lastTapped) return 'collapse';
  return target.kind === 'noRoute' ? 'hide' : 'choose';
}
