/**
 * Сколько из итога приходится на саму поездку — всё, что не ожидание.
 *
 * ПОРЯДОК ДЕЙСТВИЙ ВАЖЕН: сначала округляем, потом вычитаем. Наоборот —
 * `round(total - waitingCost)` — и чек перестаёт сходиться, потому что на
 * экране стоят округлённые слагаемые, а не исходные. Здесь остаток
 * вычисляется от ТЕХ ЖЕ чисел, которые водитель видит, и сложение их
 * взглядом всегда даёт итог.
 *
 * Разница округления оседает в «поездке», а не в «ожидании». Это намеренно:
 * ожидание — то, что оспаривают, и оно должно совпадать с отдельно
 * названной суммой за ожидание где бы она ни показывалась.
 *
 * Отрицательный результат срезается в ноль: минимальная стоимость заказа
 * или округление тарифа способны сделать итог меньше стоимости ожидания, а
 * строку с минусом водителю нечем объяснить.
 */
export function rideCostOf(total: number, waitingCost: number): number {
  const shownTotal = Math.round(numberOr0(total));
  const shownWaiting = Math.round(numberOr0(waitingCost));
  return Math.max(0, shownTotal - shownWaiting);
}

/** Мусор из сети (`NaN`, `undefined` после разбора) не должен течь в чек. */
function numberOr0(value: number): number {
  return Number.isFinite(value) ? value : 0;
}
