/**
 * @file: src/lib/map-fit.ts
 * @description:
 *   Когда карта заказа сама подгоняет охват.
 *
 *   ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. До 1.5.37 охват пересчитывался в зависимостях
 *   эффекта, среди которых стояла позиция водителя. Она приходит каждые
 *   3 секунды или каждые 10 метров, поэтому карта всю дорогу прыгала к
 *   общему плану: отмасштабировать её под себя было нельзя — следующая
 *   точка возвращала всё обратно. Ту же ошибку чинили на карте диспетчера
 *   (сервер v1.99.81, «автофит только на загрузку»).
 *
 *   Правило теперь такое: охват пересчитывается на СОБЫТИЯ, а не на
 *   движение. Событие — это смена заказа, смена стадии (цель переехала с
 *   клиента на точку назначения), появление координат, приход линии
 *   маршрута и первая позиция водителя (до неё нас на карте нет).
 *
 *   Ключ — чистая функция и покрыт тестами именно поэтому: правка, которая
 *   вернёт сюда координаты, вернёт и прыгающую карту, а заметить это по
 *   коду невозможно — только руками в машине.
 *
 * @dependencies: нет (чистая функция)
 * @created: 2026-09-04 (1.5.37)
 */

/** Всё, от чего охват карты имеет право зависеть. */
export interface MapFitInputs {
  /** Какой заказ открыт. */
  orderId: string;
  /** Стадия заказа — от неё зависит, куда ведёт маршрут. */
  status: string;
  /** Есть ли координаты подачи. */
  hasPickup: boolean;
  /** Есть ли координаты точки назначения. */
  hasDropoff: boolean;
  /** Сколько промежуточных адресов. */
  stopsCount: number;
  /** Пришла ли линия маршрута. */
  hasRoute: boolean;
  /**
   * Известна ли позиция водителя. Именно ЕСТЬ ЛИ, а не какая: координаты
   * сюда попасть не должны — с ними карта снова начнёт прыгать.
   */
  hasDriverLocation: boolean;
}

/**
 * Ключ охвата: пока он не меняется, карта принадлежит водителю.
 */
export function mapFitKey(inputs: MapFitInputs): string {
  return [
    inputs.orderId,
    inputs.status,
    inputs.hasPickup,
    inputs.hasDropoff,
    inputs.stopsCount,
    inputs.hasRoute,
    inputs.hasDriverLocation,
  ].join('|');
}
