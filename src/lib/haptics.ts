/**
 * @file: src/lib/haptics.ts
 * @description:
 *   Тактильный отклик на действия.
 *
 *   ЗАЧЕМ. Водитель нажимает кнопки, не глядя на экран — на светофоре, в
 *   движении, в перчатках. Короткая вибрация подтверждает нажатие раньше,
 *   чем ответит сервер, и снимает главную причину двойных нажатий.
 *
 *   ПОЧЕМУ `Vibration`, А НЕ `expo-haptics`. Установить нативный модуль в
 *   этом окружении не удалось: `npm install` падает с EPERM на
 *   `node_modules` (файл держит система — не песочница, с отключённой
 *   изоляцией то же самое). `Vibration` встроен в React Native, работает
 *   без пересборки и для подтверждения нажатия достаточен. Если модуль
 *   потом поставится — заменить надо будет только этот файл, вызовы по
 *   приложению не изменятся.
 *
 *   НАСТРОЙКА ВОДИТЕЛЯ УВАЖАЕТСЯ: при выключенной вибрации в настройках
 *   молчит всё, включая сигнал о новом заказе.
 *
 * @dependencies: react-native (Vibration), @/stores/settings.store
 * @created: 2026-09-01 (v1.5.17)
 */

import { Platform, Vibration } from 'react-native';
import { useSettingsStore } from '@/stores/settings.store';

function enabled(): boolean {
  // Читаем напрямую из стора, а не хуком: вибрация вызывается из
  // обработчиков событий, где хук вызвать нельзя.
  return useSettingsStore.getState().vibrationEnabled;
}

function buzz(pattern: number | number[]): void {
  if (!enabled()) return;
  // iOS игнорирует длительность и всегда даёт свой стандартный импульс —
  // паттерны там имеют смысл только как число повторов.
  if (Platform.OS === 'ios' && typeof pattern !== 'number') {
    Vibration.vibrate();
    return;
  }
  Vibration.vibrate(pattern as number[]);
}

export const haptics = {
  /** Обычное нажатие: кнопка, строка списка, переключатель. */
  tap: () => buzz(12),
  /** Главное действие принято: «Я на месте», «Начать поездку». */
  confirm: () => buzz([0, 18, 55, 28]),
  /** Успех: заказ завершён, деньги зачислены. */
  success: () => buzz([0, 22, 60, 22, 60, 45]),
  /** Отказ или ошибка: сервер не принял действие. */
  reject: () => buzz([0, 45, 70, 45]),
  /**
   * Новый заказ. Настойчиво, но не бесконечно: звонок и так продублирован
   * звуком, а непрекращающаяся вибрация в кармане мешает вести машину.
   */
  incoming: () => buzz([0, 320, 220, 320, 220, 320]),
  /** Прервать любую текущую вибрацию — например, когда заказ уже принят. */
  stop: () => Vibration.cancel(),
};
