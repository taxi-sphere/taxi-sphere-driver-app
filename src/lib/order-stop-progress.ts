/**
 * @file: src/lib/order-stop-progress.ts
 * @description:
 *   Какая промежуточная точка сейчас и что должна говорить главная кнопка.
 *
 *   ЗАЧЕМ. На заказе из трёх и более адресов кнопка говорила «ЗАВЕРШИТЬ
 *   ПОЕЗДКУ» уже на первом промежуточном: приложение не знало о точках
 *   ничего, кроме адресов. Водитель либо завершал заказ раньше времени,
 *   либо не трогал кнопку вовсе — и диспетчер не видел, где машина по
 *   маршруту.
 *
 *   ПОЧЕМУ ОТМЕТКИ ПРИХОДЯТ С СЕРВЕРА, А НЕ СЧИТАЮТСЯ ЗДЕСЬ. Прогресс,
 *   посчитанный в телефоне, теряется при перезапуске приложения и не виден
 *   диспетчеру. Поэтому у точки есть `arrivedAt` с сервера, а этот модуль
 *   только читает его.
 *
 *   СОВМЕСТИМОСТЬ СО СТАРЫМ СЕРВЕРОМ. До v1.100.2 у точки не было ни `id`,
 *   ни `arrivedAt`. Точка без `id` неотмечаема — по ней нельзя обратиться к
 *   серверу, — и такие точки правило пропускает целиком: кнопка ведёт прямо
 *   к завершению, как было раньше. Приложение обязано работать со старым
 *   сервером: обновляются они порознь.
 *
 * @dependencies: @/types/order
 * @created: 2026-09-09 (1.5.46)
 */

import type { OrderStop } from '@/types/order';

/** Точка, которую водитель проезжает сейчас. */
export interface PendingStop {
  /** Идентификатор для отметки на сервере. */
  id: string;
  /** Номер точки для подписи, с единицы. */
  number: number;
  stop: OrderStop;
}

/**
 * Первая неотмеченная точка маршрута.
 *
 * `null` — отмечать нечего: точек нет, все пройдены, или сервер старый и
 * `id` у точек не присылает.
 */
export function nextPendingStop(
  stops: OrderStop[] | null | undefined,
  status: string,
): PendingStop | null {
  // Промежуточные точки проезжают с пассажиром в машине. На подаче кнопка
  // занята другим — «Я на месте».
  if (status !== 'in_progress') return null;
  if (!Array.isArray(stops) || stops.length === 0) return null;

  for (let i = 0; i < stops.length; i++) {
    const stop = stops[i];
    if (!stop?.id) continue;
    if (stop.arrivedAt) continue;
    return { id: stop.id, number: i + 1, stop };
  }
  return null;
}

/** Сколько промежуточных точек уже отмечено — для подписи «2 из 3». */
export function passedStopsCount(stops: OrderStop[] | null | undefined): number {
  if (!Array.isArray(stops)) return 0;
  return stops.filter((s) => Boolean(s?.arrivedAt)).length;
}

/**
 * Подпись главной кнопки, когда впереди есть непройденная точка.
 *
 * Номер, а не адрес: адрес водитель читает строкой выше, а на кнопке важно
 * не потерять счёт — на заказе из пяти точек «ТОЧКА ПРОЙДЕНА» без номера не
 * отвечает на вопрос «какая именно».
 */
export function stopActionLabel(pending: PendingStop): string {
  return `ТОЧКА ${pending.number} ПРОЙДЕНА`;
}
